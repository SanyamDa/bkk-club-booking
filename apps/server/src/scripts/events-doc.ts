import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EVENT_DECLARATIONS, type EventDeclaration } from '../data/event-types.js';
import { PROPS_VALUE_PATTERN } from '../data/events.js';

/** Repo-root `docs/EVENTS.md`. */
export const EVENTS_DOC_PATH = fileURLToPath(new URL('../../../../docs/EVENTS.md', import.meta.url));

const cell = (s: string) => s.replace(/\|/g, '\\|');

/** `docs/EVENTS.md`, rendered from the declaration in `data/event-types.ts` (spec §14.2). */
export function renderEventsDoc(): string {
  const byArea = new Map<string, [string, EventDeclaration][]>();
  for (const [type, d] of Object.entries(EVENT_DECLARATIONS) as [string, EventDeclaration][]) {
    const list = byArea.get(d.area) ?? [];
    list.push([type, d]);
    byArea.set(d.area, list);
  }
  const out: string[] = [
    '# Events',
    '',
    '<!-- Generated by `npm run events:doc -w @club/server` from apps/server/src/data/event-types.ts. Do not edit by hand. -->',
    '',
    'Every event the platform records, written with `emit()` into the `events` table (spec §14.2).',
    '',
    `- \`props\` values are a number, boolean, null, or a code matching \`${PROPS_VALUE_PATTERN.source}\`. Free text goes in \`raw\`.`,
    '- An event that does not match its declaration throws in tests and goes to `events_dead_letter` in production.',
    '- Privacy classes: `none` (a code or count), `pseudonymous` (an id that links to a person or record), `personal` (identifies a person; `raw` only).',
    '',
  ];
  for (const [area, list] of byArea) {
    out.push(`## ${area}`, '', '| Event | v | Props (privacy) | Raw | Description |', '|---|---|---|---|---|');
    for (const [type, d] of list) {
      const props = Object.entries(d.props).map(([k, cls]) => `\`${k}\` (${cls})`).join(', ') || '—';
      out.push(`| \`${type}\` | ${d.v} | ${props} | ${d.raw ?? '—'} | ${cell(d.description)} |`);
    }
    out.push('');
  }
  return out.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  writeFileSync(EVENTS_DOC_PATH, renderEventsDoc());
  console.log(`wrote ${EVENTS_DOC_PATH}`);
}
